M=26;N=32;n=0:M;
xa=0:M/2;xb=ceil(M/2)-1:-1:0;xn=[xa,xb];
Xk=fft(xn,512);
X32k=fft(xn,32);
x32n=ifft(X32k);
X16k=X32k(1:2:N);
x16n=ifft(X16k,N/2);
subplot(3,2,1);stem(n,xn,'.')
title('三角波序列x(n)');xlabel('n');ylabel('x(n)');axis([0,32,0,15])
k=0:511;wk=2*k/512;
subplot(322);plot(wk,abs(Xk));title('(b)FT[x(n)]');
xlabel('\omega/\pi');ylabel('|X(e^j^\omega)|');axis([0,1,0,200])
k=0:N/2-1;
subplot(3,2,4);stem(k,abs(X16k),'.')
title('16点频域采样');xlabel('k');ylabel('|X_1_6(k)|');axis([0,8,0,200])
n1=0:N/2-1;
subplot(3,2,3);stem(n1,x16n,'.');
title('16点IDFT');xlabel('n');ylabel('x_1_6(n)');axis([0,32,0,15])
